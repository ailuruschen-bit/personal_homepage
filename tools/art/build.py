"""Generate every scene asset into public/assets/.

Usage: python3 tools/art/build.py [output directory]

Also writes src/scene/geometry.gen.ts and geometry.gen.css, the positions the
page needs, from room.py. See docs/13.
"""
import io
import os
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)

import px  # noqa: E402

# Everything is drawn on a 1x pixel grid and written out at 2x: EPX trims the
# stair-stepping off diagonals in the albedo, while lighting and bloom are computed
# at the output resolution and so come out smooth.
px.SCALE = 2

from city import build_c2  # noqa: E402
from far import build_c1, build_c3, build_sky  # noqa: E402
from room import OX, build_room, geometry  # noqa: E402


def save(im, path, lossless=False):
    """Write an asset, unless the file already holds exactly these pixels.

    WebP encoders differ between machines, so the same picture can come out as
    different bytes, and lossy WebP never decodes back to the image it was made
    from. So encode in memory, decode, and compare that with what is on disk: a
    rebuild that changed nothing then leaves git with nothing to show."""
    buf = io.BytesIO()
    if path.endswith('.webp'):
        # Sprites are small and sit on top of the room: keep them exact
        if lossless:
            im.save(buf, 'WEBP', lossless=True, quality=100, method=6)
        else:
            im.save(buf, 'WEBP', quality=90, method=6, alpha_quality=100)
    else:
        im.save(buf, 'PNG', optimize=True)
    name = os.path.basename(path)
    if os.path.exists(path):
        new = np.asarray(Image.open(io.BytesIO(buf.getvalue())).convert('RGBA'))
        old = np.asarray(Image.open(path).convert('RGBA'))
        if old.shape == new.shape and np.array_equal(old, new):
            print(f'{name:16s} unchanged')
            return
    with open(path, 'wb') as f:
        f.write(buf.getvalue())
    print(f'{name:16s} {im.size[0]}x{im.size[1]}  {len(buf.getvalue()) / 1024:.0f} KB')


def build_grain(size=192, seed=7):
    """Film grain: a tileable black-and-white noise sheet, half bright specks and half
    dark ones, with the strength carried in the alpha channel."""
    rs = np.random.RandomState(seed)
    v = rs.normal(0, 1, (size, size))
    lum = np.where(v > 0, 255, 0).astype(np.uint8)
    alpha = (np.clip(np.abs(v) * 20, 0, 60) // 6 * 6).astype(np.uint8)
    return Image.fromarray(np.dstack([lum, alpha]), 'LA')


def num(v):
    """A coordinate as TypeScript source: integers without a trailing .0."""
    v = round(float(v), 4)
    return str(int(v)) if v.is_integer() else repr(v)


def write_geometry(geo, path):
    """The scene's geometry as a TypeScript module. Generated: never edit it, edit
    room.py and rebuild."""
    w = geo['window']
    lines = [
        '// Generated by tools/art/build.py from tools/art/room.py. Do not edit:',
        '// change room.py and run `npm run art`.',
        '',
        'export interface ObjectGeometry {',
        '  /** Snap region [x0, y0, x1, y1] */',
        '  zone: [number, number, number, number];',
        '  /** Pool of light on focus: centre and radii */',
        '  light: { x: number; y: number; rx: number; ry: number };',
        '  /** Bounding box of the drawn object, when it is drawn as an object */',
        '  box?: { x: number; y: number; w: number; h: number };',
        '  /** The object alone, cut out along its own silhouette; covers `box` */',
        '  sprite?: string;',
        '  /** What stands in front of the object and stays on top of its sprite */',
        '  front?: { x: number; y: number; w: number; h: number; sprite: string };',
        '}',
        '',
        '/** The window opening and its corner radius, in scene units */',
        f"export const WINDOW = {{ x: {num(w['x'])}, y: {num(w['y'])}, w: {num(w['w'])}, h: {num(w['h'])}, r: {num(w['r'])} }};",
        '',
        '/** Width of each side extension (room-l, room-r) beyond the 480 scene */',
        f"export const SIDE = {num(geo['side'])};",
        '',
        '/** One-point perspective: the vanishing point, and the window wall as drawn face-on */',
        'export const PERSPECTIVE: { vx: number; vy: number; wall: [number, number, number, number] } = '
        f"{{ vx: {num(geo['perspective']['vx'])}, vy: {num(geo['perspective']['vy'])}, "
        f"wall: [{', '.join(num(v) for v in geo['perspective']['wall'])}] }};",
        '',
        '/** Where .cam zooms about, in scene units: the gap the camera flies through */',
        f"export const CAMERA = {{ x: {num(geo['camera']['x'])}, y: {num(geo['camera']['y'])} }};",
        '',
        '/** Every focusable object, keyed by the section it opens */',
        'export const OBJECTS: Record<string, ObjectGeometry> = {',
    ]
    for key, o in geo['objects'].items():
        z, li = o['zone'], o['light']
        parts = [
            f"zone: [{', '.join(num(v) for v in z)}]",
            f"light: {{ x: {num(li[0])}, y: {num(li[1])}, rx: {num(li[2])}, ry: {num(li[3])} }}",
        ]
        if 'box' in o:
            bx = o['box']
            parts.append(f"box: {{ x: {num(bx[0])}, y: {num(bx[1])}, w: {num(bx[2])}, h: {num(bx[3])} }}")
            parts.append(f"sprite: '{o['sprite']}'")
        if 'front' in o:
            fb = o['front']['box']
            parts.append(f"front: {{ x: {num(fb[0])}, y: {num(fb[1])}, w: {num(fb[2])}, h: {num(fb[3])}, sprite: '{o['front']['sprite']}' }}")
        lines.append(f"  {key}: {{ {', '.join(parts)} }},")
    lines += ['};', '']
    with open(path, 'w') as f:
        f.write('\n'.join(lines))
    print(f'{os.path.basename(path)}')


def pct(v):
    """Scene units as a percentage of the 480 scene."""
    return f'{round(v / 480 * 100, 5):g}%'


def write_geometry_css(geo, path):
    """Where things sit in the page: .win over the window, .cam's zoom origin and
    the glows. Appearance stays in scene.css; only position comes from here."""
    w, cam = geo['window'], geo['camera']
    rules = [
        ('.win', f"left: {pct(w['x'])}; top: {pct(w['y'])}; width: {pct(w['w'])}; height: {pct(w['h'])};\n"
                 f"  border-radius: calc(var(--u) * {num(w['r'])});"),
        ('.cam', f"transform-origin: {pct(cam['x'])} {pct(cam['y'])};"),
    ]
    for key, (x, y) in geo['marks'].items():
        sel = '.steam' if key == 'steam' else f'.{key}'
        rules.append((sel, f'left: {pct(x)}; top: {pct(y)};'))
    for key, (x, y, gw, gh) in geo['glows'].items():
        rules.append((f'.g-{key}', f'left: {pct(x)}; top: {pct(y)}; width: {pct(gw)}; height: {pct(gh)};'))
    lines = [
        '/* Generated by tools/art/build.py from tools/art/room.py. Do not edit:',
        '   change room.py and run `npm run art`. */',
        '',
    ]
    for sel, body in rules:
        lines += [f'{sel} {{', f'  {body}', '}']
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{os.path.basename(path)}')


def sprites(room, masks):
    """Each focusable object alone: the finished carriage cut out along the
    object's own silhouette and cropped to it. The 1x silhouette is upscaled the
    same way the artwork is, so its edge follows the artwork's edge."""
    k = px.SCALE
    out = {}
    for key, m in masks.items():
        a = np.asarray(m)[..., None]
        n = 1
        while n < k:
            a = px.epx(a, wrap=False)
            n *= 2
        x0, y0, x1, y1 = m.getbbox()
        box = (x0 * k, y0 * k, x1 * k, y1 * k)
        rgba = np.asarray(room.crop(box)).copy()
        rgba[..., 3] = np.where(a[y0 * k : y1 * k, x0 * k : x1 * k, 0] > 127, 255, 0)
        out[key] = Image.fromarray(rgba, 'RGBA')
    return out


def main(out, src=None):
    os.makedirs(out, exist_ok=True)
    k = px.SCALE
    save(build_sky(), os.path.join(out, 'sky.webp'))
    save(build_c1(), os.path.join(out, 'c1.webp'))
    save(build_c2(), os.path.join(out, 'c2.webp'))
    save(build_c3(), os.path.join(out, 'c3.webp'))
    room, masks = build_room()
    # What stands in front of an object is cut from the finished room; an object
    # that has something in front of it is cut from a second render without it,
    # so its sprite is whole.
    fronts = {k: m for k, m in masks.items() if k.endswith('/front')}
    whole = {k: m for k, m in masks.items() if k not in fronts}
    behind = {k: m for k, m in whole.items() if f'{k}/front' in fronts}
    cut = sprites(room, {k: m for k, m in whole.items() if k not in behind})
    if behind:
        bare, _ = build_room(over_rack=False)
        cut.update(sprites(bare, behind))
    cut.update({k.replace('/front', '-front'): im for k, im in sprites(room, fronts).items()})
    for key, im in cut.items():
        save(im, os.path.join(out, f'obj-{key}.webp'), lossless=True)
    save(room.crop((OX * k, 0, (OX + 480) * k, 480 * k)), os.path.join(out, 'room.webp'))
    save(room.crop((0, 0, OX * k, 480 * k)).convert('RGB'), os.path.join(out, 'room-l.webp'))
    save(room.crop(((OX + 480) * k, 0, (OX + 600) * k, 480 * k)).convert('RGB'), os.path.join(out, 'room-r.webp'))
    save(build_grain(), os.path.join(out, 'grain.png'))
    geo = geometry(masks)
    write_geometry(geo, os.path.join(src or out, 'geometry.gen.ts'))
    write_geometry_css(geo, os.path.join(src or out, 'geometry.gen.css'))


if __name__ == '__main__':
    # With no argument, assets go to public/assets and the geometry to src/scene.
    # Given a directory, everything goes there and the source tree is untouched:
    # that is how the review baseline and previews are built.
    if len(sys.argv) > 1:
        main(sys.argv[1])
    else:
        root = os.path.join(HERE, '..', '..')
        main(os.path.join(root, 'public', 'assets'), os.path.join(root, 'src', 'scene'))
